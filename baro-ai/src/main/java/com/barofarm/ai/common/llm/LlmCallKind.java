package com.barofarm.ai.common.llm;

/**
 * LLM 호출이 어느 경로에서 나가는지. 이 값이 타임아웃 예산과 격벽 적용 여부를 정한다.
 *
 * 경로를 나눈 근거는 {@code LlmClientConfig} 참고 — 두 경로가 견딜 수 있는 지연이 30배 다르다.
 */
public enum LlmCallKind {

    /**
     * 사용자가 화면 앞에서 응답을 기다리는 호출 (레시피 추천).
     * 3초에 끊고, 재시도하지 않으며(SDK 기본 재시도까지 끈다), 동시 호출 수를 격벽으로 제한한다.
     */
    INTERACTIVE,

    /**
     * 사람이 기다리지 않는 호출 (상품 색인 시 재료명 추출).
     * 30초까지 기다리고 최대 3회 시도한다. 호출자가 Kafka 컨슈머 하나뿐이라 격벽을 두지 않는다.
     */
    BATCH
}
